import meta from "./content/meta.json";
import { rules as lintRules } from "./lint";

const raw = import.meta.glob("./content/**/*.md", { query: "?raw", import: "default", eager: true }) as Record<string, string>;

export interface Doc {
  slug: string;
  title: string;
  body: string;
}

export interface NavGroup {
  label: string;
  docs: Doc[];
}

const docs = new Map<string, Doc>();
for (const [path, body] of Object.entries(raw)) {
  const slug = path.replace("./content/", "").replace(/\.md$/, "");
  const title = body.match(/^#\s+(.+)$/m)?.[1] ?? slug;
  docs.set(slug, { slug, title, body });
}

export const repoUrl = `https://github.com/${meta.repo}`;
export const syncedAt = meta.syncedAt;
export const INDEX_SLUG = "README";

export const getDoc = (slug: string) => docs.get(slug);
export const docPath = (slug: string) => (slug === INDEX_SLUG ? "/docs" : `/docs/${slug}`);

const pick = (prefix: string) =>
  [...docs.values()].filter((d) => d.slug.startsWith(prefix) && !d.slug.endsWith("README")).sort((a, b) => a.slug.localeCompare(b.slug));
const named = (...slugs: string[]) => slugs.map((s) => docs.get(s)).filter((d): d is Doc => !!d);

export const nav: NavGroup[] = [
  { label: "Start", docs: named(INDEX_SLUG, "overview") },
  { label: "Core rules", docs: pick("core/") },
  { label: "Languages", docs: [...named("languages/README"), ...pick("languages/")] },
  { label: "Reference", docs: named("tooling", "PURELINE_SPECIFICATION_1.7") },
];

export const languageDocs = pick("languages/");
export const shortTitle = (d: Doc) => d.title.replace(/ Code Style$/, "").replace(/^Pureline /, "");

/** Number of rule headings (`### PL-…`) in a profile. */
export const ruleCount = (d: Doc) => (d.body.match(/^###\s+PL-/gm) ?? []).length;

/** Resolves a relative markdown link from `fromSlug` to an internal route, or null if it is not a known doc. */
export function resolveLink(fromSlug: string, href: string): string | null {
  const [pathPart, hash] = href.split("#");
  const parts = fromSlug.split("/").slice(0, -1);
  for (const seg of (pathPart ?? "").split("/")) {
    if (seg === "..") parts.pop();
    else if (seg && seg !== ".") parts.push(seg);
  }
  const slug = (pathPart ? parts.join("/") : fromSlug).replace(/\.md$/, "");
  if (!docs.has(slug)) return null;
  return docPath(slug) + (hash ? `#${hash}` : "");
}

export function headings(body: string) {
  return [...body.matchAll(/^(##|###)\s+(.+)$/gm)].map((m) => ({ level: m[1]!.length, text: m[2]!.replace(/`/g, ""), id: slugify(m[2]!) }));
}

export function slugify(text: string) {
  return text
    .toLowerCase()
    .replace(/`/g, "")
    .replace(/[^\p{L}\p{N}\s-]/gu, "")
    .trim()
    .replace(/\s/g, "-");
}

export interface Rule {
  id: string;
  title: string;
  profile: string;
  profileSlug: string;
  href: string;
}

/** Rule IDs the Pureline checker in the editor enforces, read from the checker itself. */
export const checkedRules = new Set(lintRules.map((r) => r.id));

/** Every rule in the guide: headings (`### PL-…`) and the core table rows (`| PL-CORE-… |`). */
export const rules: Rule[] = (() => {
  const byId = new Map<string, Rule>();
  for (const doc of docs.values()) {
    if (doc.slug.startsWith("PURELINE") || doc.slug.endsWith("README")) continue;
    const isCore = doc.slug.startsWith("core/") || doc.slug === "overview" || doc.slug === "tooling";
    const profileDoc = isCore ? null : docs.get(doc.slug.split("/").slice(0, 2).join("/"));
    const profile = isCore ? "Core" : profileDoc ? shortTitle(profileDoc) : doc.slug;
    const profileSlug = isCore ? "core" : doc.slug.split("/").slice(0, 2).join("/");
    for (const line of doc.body.split("\n")) {
      const heading = /^#{2,4}\s+(PL-[A-Z0-9-]+)\s+—\s+(.+)$/.exec(line);
      const row = /^\|\s*(PL-[A-Z0-9-]+)\s*\|\s*(.+?)\s*\|\s*$/.exec(line);
      const match = heading ?? row;
      if (!match || byId.has(match[1]!)) continue;
      const id = match[1]!;
      const title = match[2]!.replace(/`/g, "");
      const anchor = heading ? `#${slugify(`${id} — ${title}`)}` : "";
      byId.set(id, { id, title, profile, profileSlug, href: docPath(doc.slug) + anchor });
    }
  }
  return [...byId.values()].sort((a, b) => (a.profile === b.profile ? a.id.localeCompare(b.id) : a.profile === "Core" ? -1 : b.profile === "Core" ? 1 : a.profile.localeCompare(b.profile)));
})();

/** Profiles in the order they appear in the rule index. */
export const ruleProfiles = [...new Map(rules.map((r) => [r.profile, r.profileSlug])).entries()].map(([label, slug]) => ({ label, slug }));

